def cards(items, cls="card"):
    return '<div class="card-grid">'+"".join(f'<div class="{cls}" style="border-top:3px solid {c}"><h4 style="color:{c}">{t}</h4>{b}</div>' for c,t,b in items)+'</div>'

def table(head, rows):
    h="".join(f"<th>{x}</th>" for x in head)
    r="".join("<tr>"+"".join(f"<td>{x}</td>" for x in row)+"</tr>" for row in rows)
    return f'<div class="table-wrap"><table><thead><tr>{h}</tr></thead><tbody>{r}</tbody></table></div>'

def flow(steps):
    return '<div class="flow">'+'<span class="arr">→</span>'.join(f'<div class="step">{s}</div>' for s in steps)+'</div>'

